#!/usr/bin/env python3
"""Build explain.js: situation library for the Reactive check result."""
import json
from pathlib import Path

SPECS = []


def add(i, crit, sev, when, ru, en):
    SPECS.append({"id": i, "crit": bool(crit), "sev": sev, "when": when, "ru": ru, "en": en})


def frames(p):
    """Seven readings of the same situation. Pieces are full sentences."""
    h, h2, h3 = p["h"], p["h2"], p["h3"]
    fact, mech, sale, watch, calm = p["fact"], p["mech"], p["sale"], p["watch"], p["calm"]
    return [
        [h, fact + " " + mech, watch],
        [h2, mech + " " + sale, watch],
        [h3, fact + " " + sale, calm],
        [h, calm + " " + mech, watch],
        [h2, sale + " " + fact, calm],
        [h3, mech + " " + calm, watch],
        [h2, fact + " " + calm, watch],
    ]


def both(i, crit, sev, when, ru, en):
    add(i, crit, sev, when, frames(ru), frames(en))


